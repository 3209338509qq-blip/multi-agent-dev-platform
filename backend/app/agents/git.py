"""Git Agent：Git 操作（branch / commit / merge）。

基于阶段产物执行 git 操作，记录 commit 到数据库。
"""
from __future__ import annotations
import logging
import subprocess
from pathlib import Path
from typing import Any

from app.agents import AgentContext, AgentResult, BaseAgent
from app.models import AgentRole, TaskStatus

logger = logging.getLogger("madp.agents.git")


class GitAgent(BaseAgent):
    role = AgentRole.GIT

    async def run(self, ctx: AgentContext) -> AgentResult:
        try:
            repo_path = Path(ctx.workspace_path)
            src_path = repo_path / "src"

            if not src_path.exists():
                return AgentResult(status=TaskStatus.FAILED, error="src/ 目录不存在")

            # 确保是 git 仓库
            if not (repo_path / ".git").exists():
                subprocess.run(["git", "init"], cwd=str(repo_path), capture_output=True, check=True)
                subprocess.run(["git", "config", "user.email", "agent@madp.local"], cwd=str(repo_path), capture_output=True)
                subprocess.run(["git", "config", "user.name", "MADP Agent"], cwd=str(repo_path), capture_output=True)

            # 添加所有文件并提交
            subprocess.run(["git", "add", "-A"], cwd=str(repo_path), capture_output=True, check=True)

            # 检查是否有变更
            status = subprocess.run(
                ["git", "status", "--porcelain"],
                cwd=str(repo_path), capture_output=True, text=True,
            )
            if not status.stdout.strip():
                return AgentResult(
                    status=TaskStatus.SUCCESS,
                    output_data={"message": "No changes to commit", "hash": None},
                )

            commit_msg = (ctx.input_data or {}).get("commit_message", "feat: auto-generated by MADP agents")
            result = subprocess.run(
                ["git", "commit", "-m", commit_msg],
                cwd=str(repo_path), capture_output=True, text=True, check=True,
            )

            # 获取 commit hash
            hash_result = subprocess.run(
                ["git", "rev-parse", "HEAD"],
                cwd=str(repo_path), capture_output=True, text=True, check=True,
            )
            commit_hash = hash_result.stdout.strip()

            logger.info("Git commit: %s (%s)", commit_hash[:8], commit_msg)

            return AgentResult(
                status=TaskStatus.SUCCESS,
                output_data={"hash": commit_hash, "message": commit_msg, "output": result.stdout[-500:]},
            )

        except subprocess.CalledProcessError as e:
            logger.exception("Git Agent failed")
            return AgentResult(status=TaskStatus.FAILED, error=f"Git error: {e.stderr[:500] if e.stderr else str(e)}")
        except Exception as e:
            logger.exception("Git Agent failed")
            return AgentResult(status=TaskStatus.FAILED, error=str(e))
